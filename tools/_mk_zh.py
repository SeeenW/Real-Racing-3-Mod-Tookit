def main() -> int:
    source = json.load(open(os.path.join(I18N, "_source.json"), encoding="utf-8"))
    keys = list(source)
    if len(keys) != len(ZH):
        print(f"source has {len(keys)} strings, table has {len(ZH)}")
        missing = [i for i in range(len(keys)) if i not in ZH]
        extra = [i for i in ZH if i >= len(keys)]
        print("missing indices:", missing[:20], "extra:", extra[:20])
        return 1

    table = {keys[index]: ZH[index] for index in ZH}
    path = os.path.join(I18N, "zh-Hans.json")
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        json.dump(table, handle, ensure_ascii=False, indent=1, sort_keys=True)
        handle.write("\n")
    print(f"{len(table)} translations -> {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
